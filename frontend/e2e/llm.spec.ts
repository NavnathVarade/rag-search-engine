import { expect, test } from '@playwright/test'
import path from 'node:path'

// The API here is configured with LLM_PROVIDER=openai_compatible pointing at e2e/fake_llm.py, a local stand-in for the
// model API. This verifies the wiring and the rendering of a generated, cited answer, not answer quality.
test('a configured model replaces the stub: Markdown renders and [n] markers open the cited source', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Answers generated by stand-in-model')).toBeVisible()
  await expect(page.getByText('Answers use the offline stub')).toHaveCount(0)

  await page.goto('/add')
  await page.getByLabel('Choose files to upload').setInputFiles(path.join(import.meta.dirname, 'fixtures', 'kubernetes.md'))
  await expect(page.getByText('Added', { exact: true })).toBeVisible()

  await page.goto('/chat')
  await page.getByLabel('Your question').fill('What happens when a container fails in Kubernetes?')
  await page.getByRole('button', { name: 'Send question' }).click()
  const answer = page.locator('.prose-answer')
  await expect(answer.locator('strong')).toHaveText('kubelet')
  await expect(answer.locator('code')).toHaveText('restartPolicy')
  await expect(answer.locator('li')).toHaveCount(2)
  await expect(page.getByText('Offline stub answer.')).toHaveCount(0)
  await expect(page.getByText(/stand-in-model · 1 passage retrieved/)).toBeVisible()

  const chip = answer.getByRole('button', { name: 'Open source 1' }).first()
  await chip.click()
  await expect(page.getByText(/CrashLoopBackOff/).first()).toBeVisible()
  await page.screenshot({ path: path.join(import.meta.dirname, 'shots', '12-chat-generated.png'), fullPage: true })

  // with nothing relevant indexed the real answerer never calls the model
  await page.getByLabel('Your question').fill('What is the airspeed velocity of an unladen swallow?')
  await page.getByRole('button', { name: 'Send question' }).click()
  await expect(page.getByText('Not enough evidence.')).toBeVisible()
})
